import AppKit
import UniformTypeIdentifiers

/// Превращает содержимое пастборда в вещи для полки. Файлы — ссылкой,
/// картинки и векторы сохраняем себе файлом, простой текст оставляем текстом.
enum Ingest {

    static let svgType = NSPasteboard.PasteboardType("public.svg-image")

    static let acceptedTypes: [NSPasteboard.PasteboardType] = [
        .fileURL, .URL, svgType, .tiff, .png, .rtf, .string, .html
    ]

    /// Метки, которыми менеджеры паролей просят не сохранять содержимое.
    private static let secretMarks = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType"
    ].map(NSPasteboard.PasteboardType.init(rawValue:))

    static func canAccept(_ pb: NSPasteboard) -> Bool {
        pb.availableType(from: acceptedTypes) != nil
    }

    static func isSecret(_ pb: NSPasteboard) -> Bool {
        pb.availableType(from: secretMarks) != nil
    }

    static func items(from pb: NSPasteboard, store: ShelfStore,
                      source: ShelfSource = .drop) -> [ShelfItem] {
        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return urls.map { ShelfItem(url: $0.standardizedFileURL, owned: false, source: source) }
        }

        if let svg = pb.data(forType: svgType),
           let file = write(svg, name: "Вектор \(stamp())", ext: "svg", store: store) {
            return [ShelfItem(url: file, owned: true, source: source)]
        }

        if let images = pb.readObjects(forClasses: [NSImage.self], options: nil) as? [NSImage],
           let image = images.first,
           let file = writePNG(image, store: store) {
            return [ShelfItem(url: file, owned: true, source: source)]
        }

        if let links = pb.readObjects(forClasses: [NSURL.self], options: nil) as? [URL],
           let link = links.first, link.scheme != nil,
           let file = writeWebloc(link, store: store) {
            return [ShelfItem(url: file, owned: true, source: source)]
        }

        if let text = pb.string(forType: .string), !text.isEmpty {
            let head = text.trimmingCharacters(in: .whitespacesAndNewlines)
            // Скопированный SVG-код — это вектор, а не просто текст.
            let isSVG = head.hasPrefix("<svg")
                || (head.hasPrefix("<?xml") && head.contains("<svg"))
            if isSVG, let data = text.data(using: .utf8),
               let file = write(data, name: "Вектор \(stamp())", ext: "svg", store: store) {
                return [ShelfItem(url: file, owned: true, source: source)]
            }
            return [ShelfItem(text: text, source: source)]
        }
        return []
    }

    // MARK: запись

    private static func write(_ data: Data, name: String, ext: String,
                              store: ShelfStore) -> URL? {
        let url = store.blobURL(name: name, ext: ext)
        do { try data.write(to: url); return url } catch { return nil }
    }

    /// Пишем строго 8 бит на канал. Из буфера часто прилетает 16-битный TIFF
    /// (широкий цвет), и если сохранить его как есть, получится 16-битный PNG —
    /// такие принимают не все программы, куда потом тащат картинку.
    private static func writePNG(_ image: NSImage, store: ShelfStore) -> URL? {
        guard let tiff = image.tiffRepresentation,
              let source = NSBitmapImageRep(data: tiff),
              let png = eightBitPNG(from: source) else { return nil }
        return write(png, name: "Картинка \(stamp())", ext: "png", store: store)
    }

    private static func eightBitPNG(from source: NSBitmapImageRep) -> Data? {
        if source.bitsPerSample == 8 {
            return source.representation(using: .png, properties: [:])
        }
        let w = source.pixelsWide, h = source.pixelsHigh
        guard w > 0, h > 0,
              let out = NSBitmapImageRep(
                bitmapDataPlanes: nil, pixelsWide: w, pixelsHigh: h,
                bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)
        else { return nil }
        out.size = NSSize(width: w, height: h)

        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: out)
        source.draw(in: NSRect(x: 0, y: 0, width: w, height: h),
                    from: .zero, operation: .copy, fraction: 1,
                    respectFlipped: true, hints: [.interpolation: NSNumber(value: NSImageInterpolation.none.rawValue)])
        NSGraphicsContext.restoreGraphicsState()
        return out.representation(using: .png, properties: [:])
    }

    private static func writeWebloc(_ link: URL, store: ShelfStore) -> URL? {
        let plist: [String: Any] = ["URL": link.absoluteString]
        guard let data = try? PropertyListSerialization.data(fromPropertyList: plist,
                                                            format: .xml, options: 0)
        else { return nil }
        return write(data, name: link.host ?? "Ссылка", ext: "webloc", store: store)
    }

    private static func stamp() -> String {
        let f = DateFormatter()
        f.dateFormat = "dd-MM HH-mm-ss"
        return f.string(from: Date())
    }
}
